/** 派单方（谁派的活）对应哪家的 logo：Claude 桌面端 → claude-desktop，Claude Code → claude，Grok Bot → grokbot */
export function dispatcherAgent(kind?: string) {
  if (kind === 'claude-desktop' || kind === 'grok') {
    return kind === 'grok' ? 'grokbot' : kind
  }
  return kind?.startsWith('claude') ? 'claude' : undefined
}

/** Agent 的原版 logo；不认识的 Agent 用通用机器人图标，普通 shell（agent 为空）不画 */
export function AgentLogo({
  agent,
  className,
}: {
  agent?: string | null
  className?: string
}) {
  // useId 带特殊字符，放进 url(#…) 前清掉
  const id = `agent-logo-${useId().replace(/[^\w-]/g, '')}`
  if (!agent) return null
  const logo = LOGOS[agent.toLowerCase()]
  if (logo && 'img' in logo) {
    return (
      <img
        src={logo.img}
        alt={logo.name}
        title={logo.name}
        className={cn(
          'size-3.5 shrink-0 rounded-[3px] object-contain',
          className
        )}
      />
    )
  }
  if (!logo)
    return (
      <Bot
        aria-label={agent}
        className={cn('size-3.5 shrink-0 text-muted-foreground', className)}
      />
    )
  return (
    <svg
      viewBox='0 0 24 24'
      role='img'
      aria-label={logo.name}
      className={cn('size-3.5 shrink-0', className)}
    >
      <title>{logo.name}</title>
      {logo.draw(id)}
    </svg>
  )
}

/** logo + 名字，任务列表、标签这类一行字里用 */
export function AgentName({
  agent,
  className,
}: {
  agent?: string | null
  className?: string
}) {
  if (!agent) return null
  return (
    <span
      className={cn('inline-flex items-center gap-1 align-middle', className)}
    >
      <AgentLogo agent={agent} className='size-3.5' />
      <span>{LOGOS[agent.toLowerCase()]?.name ?? agent}</span>
    </span>
  )
}
