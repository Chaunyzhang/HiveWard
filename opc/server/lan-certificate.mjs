import {
  generateKeyPairSync,
  randomBytes,
  sign,
  X509Certificate,
  createPrivateKey
} from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync, chmodSync } from 'node:fs'
import { join } from 'node:path'

const der = (tag, ...parts) => {
  const body = Buffer.concat(parts.map((p) => (Buffer.isBuffer(p) ? p : Buffer.from(p))))
  const bytes = []
  for (let n = body.length; n; n >>>= 8) {
    bytes.unshift(n & 255)
  }
  const length = body.length < 128 ? [body.length] : [128 | bytes.length, ...bytes]
  return Buffer.concat([Buffer.from([tag, ...length]), body])
}
const sequence = (...parts) => der(0x30, ...parts)
const oid = (hex) => der(6, Buffer.from(hex, 'hex'))
const algorithm = sequence(oid('2a8648ce3d040302'))
const time = (date) => {
  const value = date
    .toISOString()
    .replace(/[-:T]/g, '')
    .replace(/\.\d+Z$/, 'Z')
  return date.getUTCFullYear() < 2050 ? der(0x17, value.slice(2)) : der(0x18, value)
}
const pem = (label, bytes) =>
  `-----BEGIN ${label}-----\n${bytes
    .toString('base64')
    .match(/.{1,64}/g)
    .join('\n')}\n-----END ${label}-----\n`

// Minimal RFC 5280 self-signed certificate; keys and signatures are generated by Node/OpenSSL.
export function generateLanCertificate() {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' })
  const name = sequence(der(0x31, sequence(oid('550403'), der(0x0c, 'HiveWard LAN'))))
  const serial = randomBytes(20)
  serial[0] &= 0x7f
  serial[0] |= 1
  const start = new Date(Date.now() - 86400000)
  const end = new Date(start)
  end.setUTCFullYear(end.getUTCFullYear() + 20)
  const tbs = sequence(
    der(0xa0, der(2, [2])),
    der(2, serial),
    algorithm,
    name,
    sequence(time(start), time(end)),
    name,
    publicKey.export({ type: 'spki', format: 'der' })
  )
  const certificate = sequence(
    tbs,
    algorithm,
    der(3, Buffer.from([0]), sign('sha256', tbs, privateKey))
  )
  return {
    key: privateKey.export({ type: 'pkcs8', format: 'pem' }),
    cert: pem('CERTIFICATE', certificate)
  }
}

export function loadLanCertificate(directory) {
  mkdirSync(directory, { recursive: true, mode: 0o700 })
  const file = join(directory, 'lan-identity.json')
  let value
  try {
    value = JSON.parse(readFileSync(file, 'utf8'))
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw error
    }
    const generated = generateLanCertificate()
    try {
      writeFileSync(file, JSON.stringify(generated), { flag: 'wx', mode: 0o600 })
    } catch (e) {
      if (e.code !== 'EEXIST') {
        throw e
      }
    }
    value = JSON.parse(readFileSync(file, 'utf8'))
  }
  chmodSync(file, 0o600)
  const certificate = new X509Certificate(value.cert)
  if (
    !certificate.checkPrivateKey(createPrivateKey(value.key)) ||
    !certificate.verify(certificate.publicKey)
  ) {
    throw new Error('LAN 证书与私钥不匹配，请恢复身份文件或重新加入组织')
  }
  return { ...value, fingerprint: certificate.fingerprint256.replaceAll(':', '').toLowerCase() }
}
