import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { isPluginSourceModulePath } from '../../shared/plugins/frames/plugin-frame-source-modules'
import { parsePluginManifest } from '../../shared/plugins/manifest/plugin-manifest'

/** Plugin-relative folder `hiveward plugin types` owns; dev hashing and loading skip it. */
export const PLUGIN_TYPES_DIR = '.hiveward/types'

/** Host, frame (`window.hiveward`), worker (`hiveward/worker`) and test kit (`hiveward/testing`) typings,
 *  under resources/plugins/types. */
const PLUGIN_SURFACE_TYPINGS = [
  { dir: 'hiveward-host', file: 'hiveward-host.d.ts' },
  { dir: 'hiveward-frame', file: 'hiveward-frame.d.ts' },
  { dir: 'hiveward-worker', file: 'hiveward-worker.d.ts' },
  { dir: 'hiveward-services', file: 'hiveward-services.d.ts' },
  { dir: 'hiveward-testing', file: 'hiveward-testing.d.ts' }
] as const

// Why one tsconfig the plugin extends: the typings and JSX settings then track the HiveWard that wrote
// them, and a plugin's own `include` cannot drop them (typeRoots resolve against this file).
const TYPES_TSCONFIG = {
  compilerOptions: {
    strict: true,
    noEmit: true,
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    allowImportingTsExtensions: true,
    isolatedModules: true,
    jsx: 'react-jsx',
    jsxImportSource: 'hiveward',
    lib: ['ES2022', 'DOM'],
    // tsc 7 reaches `hiveward` via the symlinked path and the typeRoots via the realpath, so a plugin
    // under a symlink (macOS /tmp) loads the typings twice (TS2300 duplicate identifiers).
    preserveSymlinks: true,
    typeRoots: ['.'],
    types: ['hiveward', ...PLUGIN_SURFACE_TYPINGS.map(({ dir }) => dir)]
  }
}

/** The `hiveward` module's typings, split by size; written as one `hiveward/index.d.ts`. */
export const HIVEWARD_MODULE_TYPINGS = [
  'hiveward.d.ts',
  'hiveward-components.d.ts',
  'hiveward-components-layout.d.ts',
  'hiveward-components-data.d.ts'
] as const

const GENERATED_NOTE =
  '// Written by `hiveward plugin types`; regenerated by `hiveward plugin dev load`. Do not edit.\n'

const defaultAppRoot = (): string => join(__dirname, '..', '..', '..')

/** HiveWard's author typings; `out/cli/plugin-authoring` and `src/cli/plugin-authoring` both sit
 *  three levels under the app root, and packaging unpacks resources/plugins/{declarative,types}. */
export async function readHiveWardPluginTypings(appRoot = defaultAppRoot()): Promise<string> {
  const parts = await Promise.all(
    HIVEWARD_MODULE_TYPINGS.map((file) =>
      readFile(join(appRoot, 'resources', 'plugins', 'declarative', file), 'utf8')
    )
  )
  return parts.join('\n')
}

/** Every typings file `hiveward plugin types` writes, keyed by its `.hiveward/types` folder. */
export async function readHiveWardAuthorTypings(
  appRoot = defaultAppRoot()
): Promise<Record<string, string>> {
  const typings: Record<string, string> = { hiveward: await readHiveWardPluginTypings(appRoot) }
  for (const { dir, file } of PLUGIN_SURFACE_TYPINGS) {
    typings[dir] = await readFile(join(appRoot, 'resources', 'plugins', 'types', file), 'utf8')
  }
  return typings
}

/** Writes `.hiveward/types/<folder>/index.d.ts` per typings file, a `tsconfig.json` listing them, and
 *  a `.gitignore` that ignores `.hiveward/`. */
export async function writePluginTypeFiles(pluginDir: string, appRoot?: string): Promise<string[]> {
  const typings = await readHiveWardAuthorTypings(appRoot)
  const files: Record<string, string> = { '.hiveward/.gitignore': '*\n' }
  for (const [dir, text] of Object.entries(typings)) {
    await mkdir(join(pluginDir, '.hiveward', 'types', dir), { recursive: true })
    files[`${PLUGIN_TYPES_DIR}/${dir}/index.d.ts`] = GENERATED_NOTE + text
  }
  files[`${PLUGIN_TYPES_DIR}/tsconfig.json`] = `${JSON.stringify(TYPES_TSCONFIG, null, 2)}\n`
  for (const [file, content] of Object.entries(files)) {
    await writeFile(join(pluginDir, ...file.split('/')), content)
  }
  return Object.keys(files)
}

/** A folder gets typings on dev load when it has them, its tsconfig wants them, or it has a
 *  TS/TSX entry or a components panel. */
export async function pluginFolderWantsTypes(pluginDir: string): Promise<boolean> {
  if (existsSync(join(pluginDir, '.hiveward', 'types'))) {
    return true
  }
  const tsconfig = await readFile(join(pluginDir, 'tsconfig.json'), 'utf8').catch(() => '')
  if (tsconfig.includes(PLUGIN_TYPES_DIR)) {
    return true
  }
  const raw = await readFile(join(pluginDir, 'hiveward-plugin.json'), 'utf8').catch(() => null)
  let parsed: unknown = null
  try {
    parsed = raw === null ? null : JSON.parse(raw)
  } catch {
    return false
  }
  const manifest = parsePluginManifest(parsed)
  if (!manifest.ok) {
    return false
  }
  const { panels, customEditors } = manifest.manifest.contributes
  return (
    panels.some((panel) => panel.ui === 'components') ||
    [...panels, ...customEditors].some((item) => isPluginSourceModulePath(item.entry))
  )
}
