import { clipboard, nativeImage } from 'electron'
import { watchClipboardSequence } from './clipboard-process'
import {
  macClipboardSequenceSpec,
  readMacClipboardFiles,
  writeMacClipboardFiles
} from './clipboard-macos'
import {
  readWindowsClipboardFiles,
  windowsClipboardSequenceSpec,
  writeWindowsClipboardFiles
} from './clipboard-windows'

export type OpcClipboardPayload =
  | { kind: 'text'; text: string; html?: string; rtf?: string }
  | { kind: 'image'; png: Buffer }
  | { kind: 'files'; paths: string[] }

export type OpcClipboardRead =
  | OpcClipboardPayload
  | { kind: 'text' | 'image' | 'files'; skipped: string }

export type OpcClipboardAdapter = {
  watch: (onChange: () => void) => () => void
  read: () => Promise<OpcClipboardRead>
  write: (payload: OpcClipboardPayload, options?: { signal?: AbortSignal }) => Promise<void>
  close: () => void
}

type ClipboardKind = OpcClipboardPayload['kind']

const TEXT_MAX_BYTES = 16 * 1024 * 1024
const PNG_MAX_BYTES = 64 * 1024 * 1024
const MAC_EXCLUDED_FORMATS = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType'
]
const WINDOWS_EXCLUDED_FORMAT = 'ExcludeClipboardContentFromMonitorProcessing'
const WINDOWS_ZERO_DWORD_FORMATS = ['CanIncludeInClipboardHistory', 'CanUploadToCloudClipboard']

export function createOpcClipboardAdapter(): OpcClipboardAdapter {
  const platform = process.platform
  const watchers = new Set<() => void>()
  const processes = new Set<AbortController>()
  let closed = false

  function watch(onChange: () => void): () => void {
    if (closed || (platform !== 'darwin' && platform !== 'win32')) {
      return () => {}
    }
    const spec = platform === 'darwin' ? macClipboardSequenceSpec() : windowsClipboardSequenceSpec()
    let stopped = false
    const stopSequence = watchClipboardSequence(spec, onChange)
    const stop = (): void => {
      if (stopped) {
        return
      }
      stopped = true
      watchers.delete(stop)
      stopSequence()
    }
    watchers.add(stop)
    return stop
  }

  async function withProcess<T>(
    operation: (signal: AbortSignal) => Promise<T>,
    signal?: AbortSignal
  ): Promise<T> {
    if (closed || signal?.aborted) {
      throw new Error('clipboard_closed')
    }
    const controller = new AbortController()
    const abort = (): void => controller.abort()
    signal?.addEventListener('abort', abort, { once: true })
    processes.add(controller)
    try {
      return await operation(controller.signal)
    } finally {
      signal?.removeEventListener('abort', abort)
      processes.delete(controller)
    }
  }

  async function read(): Promise<OpcClipboardRead> {
    if (closed) {
      return { kind: 'text', skipped: 'read_failed' }
    }
    if (platform !== 'darwin' && platform !== 'win32') {
      return { kind: 'text', skipped: 'unsupported_platform' }
    }
    let kind: ClipboardKind = 'text'
    try {
      const formats = clipboard.availableFormats()
      kind = inferClipboardKind(formats, platform)
      if (hasExcludedFormat(formats, platform)) {
        return { kind, skipped: 'excluded_format' }
      }
      if (kind === 'files') {
        return await readFiles(platform, withProcess)
      }
      if (kind === 'image') {
        return readImage()
      }
      return readText()
    } catch {
      return { kind, skipped: 'read_failed' }
    }
  }

  async function write(
    payload: OpcClipboardPayload,
    options?: { signal?: AbortSignal }
  ): Promise<void> {
    if (closed || options?.signal?.aborted) {
      throw new Error('clipboard_closed')
    }
    if (platform !== 'darwin' && platform !== 'win32') {
      throw new Error('unsupported_platform')
    }
    assertPayloadWithinLimits(payload)
    try {
      if (payload.kind === 'text') {
        clipboard.write({ text: payload.text, html: payload.html, rtf: payload.rtf })
        return
      }
      if (payload.kind === 'image') {
        const image = nativeImage.createFromBuffer(payload.png)
        if (image.isEmpty()) {
          throw new Error('clipboard_write_failed')
        }
        clipboard.write({ image })
        return
      }
      await withProcess(
        (signal) =>
          platform === 'darwin'
            ? writeMacClipboardFiles(payload.paths, signal)
            : writeWindowsClipboardFiles(payload.paths, signal),
        options?.signal
      )
    } catch {
      throw new Error('clipboard_write_failed')
    }
  }

  function close(): void {
    if (closed) {
      return
    }
    closed = true
    for (const stop of Array.from(watchers)) {
      stop()
    }
    watchers.clear()
    for (const controller of processes) {
      controller.abort()
    }
    processes.clear()
  }

  return { watch, read, write, close }
}

async function readFiles(
  platform: NodeJS.Platform,
  withProcess: <T>(operation: (signal: AbortSignal) => Promise<T>) => Promise<T>
): Promise<OpcClipboardRead> {
  if (platform === 'darwin') {
    const paths = readMacClipboardFiles()
    return paths.length > 0 ? { kind: 'files', paths } : { kind: 'files', skipped: 'read_failed' }
  }
  const paths = await withProcess((signal) => readWindowsClipboardFiles(signal))
  return paths.length > 0 ? { kind: 'files', paths } : { kind: 'files', skipped: 'read_failed' }
}

function readImage(): OpcClipboardRead {
  const image = clipboard.readImage()
  if (image.isEmpty()) {
    return { kind: 'image', skipped: 'read_failed' }
  }
  const png = image.toPNG()
  return png.byteLength > PNG_MAX_BYTES
    ? { kind: 'image', skipped: 'content_too_large' }
    : { kind: 'image', png }
}

function readText(): OpcClipboardRead {
  const text = clipboard.readText()
  const html = clipboard.readHTML()
  const rtf = clipboard.readRTF()
  if ([text, html, rtf].some((value) => Buffer.byteLength(value, 'utf8') > TEXT_MAX_BYTES)) {
    return { kind: 'text', skipped: 'content_too_large' }
  }
  return {
    kind: 'text',
    text,
    ...(html ? { html } : {}),
    ...(rtf ? { rtf } : {})
  }
}

function inferClipboardKind(formats: readonly string[], platform: NodeJS.Platform): ClipboardKind {
  const fileFormats =
    platform === 'darwin'
      ? ['NSFilenamesPboardType', 'public.file-url']
      : ['CF_HDROP', 'FileNameW', 'Shell IDList Array']
  if (fileFormats.some((format) => formats.includes(format))) {
    return 'files'
  }
  if (
    formats.some(
      (format) =>
        format.startsWith('image/') ||
        format === 'public.png' ||
        format === 'public.tiff' ||
        format === 'NSPasteboardTypePNG' ||
        format === 'NSPasteboardTypeTIFF' ||
        format === 'CF_DIB' ||
        format === 'CF_DIBV5' ||
        format === 'CF_BITMAP' ||
        format === 'PNG'
    )
  ) {
    return 'image'
  }
  return 'text'
}

function hasExcludedFormat(formats: readonly string[], platform: NodeJS.Platform): boolean {
  if (platform === 'darwin') {
    return MAC_EXCLUDED_FORMATS.some((format) => formats.includes(format) || clipboard.has(format))
  }
  if (formats.includes(WINDOWS_EXCLUDED_FORMAT) || clipboard.has(WINDOWS_EXCLUDED_FORMAT)) {
    return true
  }
  return WINDOWS_ZERO_DWORD_FORMATS.some((format) => {
    if (!formats.includes(format) && !clipboard.has(format)) {
      return false
    }
    const value = clipboard.readBuffer(format)
    return value.byteLength !== 4 || value.readUInt32LE(0) === 0
  })
}

function assertPayloadWithinLimits(payload: OpcClipboardPayload): void {
  if (payload.kind === 'image') {
    if (payload.png.byteLength > PNG_MAX_BYTES) {
      throw new Error('content_too_large')
    }
    return
  }
  if (payload.kind !== 'text') {
    return
  }
  if (
    [payload.text, payload.html ?? '', payload.rtf ?? ''].some(
      (value) => Buffer.byteLength(value, 'utf8') > TEXT_MAX_BYTES
    )
  ) {
    throw new Error('content_too_large')
  }
}
