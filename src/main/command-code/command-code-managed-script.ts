import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%HIVEWARD_AGENT_HOOK_PORT%"=="" if defined HIVEWARD_AGENT_HOOK_ENDPOINT if exist "%HIVEWARD_AGENT_HOOK_ENDPOINT%" call "%HIVEWARD_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%HIVEWARD_AGENT_HOOK_TOKEN%"=="" if not "%HIVEWARD_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\hiveward-dev\\agent-hooks" for /r "%APPDATA%\\hiveward-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%HIVEWARD_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\hiveward-dev-wt" for /d %%P in ("%APPDATA%\\hiveward-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%HIVEWARD_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\hiveward\\agent-hooks" for /r "%APPDATA%\\hiveward\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%HIVEWARD_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%HIVEWARD_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set HIVEWARD_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%HIVEWARD_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__hiveward_read_ancestor_var() {',
    '  __hiveward_name="$1"',
    '  __hiveward_pid="${PPID:-}"',
    '  while [ -n "$__hiveward_pid" ] && [ "$__hiveward_pid" != "0" ] && [ "$__hiveward_pid" != "1" ]; do',
    '    __hiveward_value=""',
    '    if [ -r "/proc/$__hiveward_pid/environ" ]; then',
    '      __hiveward_value=$(tr "\\000" "\\n" < "/proc/$__hiveward_pid/environ" 2>/dev/null | sed -n "s/^${__hiveward_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__hiveward_value" ]; then',
    '      __hiveward_value=$(ps eww -p "$__hiveward_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__hiveward_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__hiveward_value" ]; then',
    '      printf "%s\\n" "$__hiveward_value"',
    '      return 0',
    '    fi',
    '    __hiveward_pid=$(ps -o ppid= -p "$__hiveward_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__hiveward_fill_from_ancestor() {',
    '  __hiveward_name="$1"',
    '  case "$__hiveward_name" in',
    '    HIVEWARD_AGENT_HOOK_ENDPOINT) [ -z "${HIVEWARD_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    HIVEWARD_AGENT_HOOK_PORT) [ -z "${HIVEWARD_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    HIVEWARD_AGENT_HOOK_TOKEN) [ -z "${HIVEWARD_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    HIVEWARD_AGENT_HOOK_ENV) [ -z "${HIVEWARD_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    HIVEWARD_AGENT_HOOK_VERSION) [ -z "${HIVEWARD_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    HIVEWARD_PANE_KEY) [ -z "${HIVEWARD_PANE_KEY:-}" ] || return 0 ;;',
    '    HIVEWARD_TAB_ID) [ -z "${HIVEWARD_TAB_ID:-}" ] || return 0 ;;',
    '    HIVEWARD_WORKTREE_ID) [ -z "${HIVEWARD_WORKTREE_ID:-}" ] || return 0 ;;',
    '    HIVEWARD_AGENT_LAUNCH_TOKEN) [ -z "${HIVEWARD_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __hiveward_value=$(__hiveward_read_ancestor_var "$__hiveward_name") || return 0',
    '  [ -n "$__hiveward_value" ] && export "$__hiveward_name=$__hiveward_value"',
    '}',
    '__hiveward_endpoint_value() {',
    '  __hiveward_endpoint_name="$1"',
    '  __hiveward_endpoint_path="$2"',
    '  sed -n "s/^${__hiveward_endpoint_name}=//p" "$__hiveward_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__hiveward_fill_from_endpoint_file() {',
    '  __hiveward_endpoint_path="$1"',
    '  [ -r "$__hiveward_endpoint_path" ] || return 0',
    '  __hiveward_endpoint_port=$(__hiveward_endpoint_value HIVEWARD_AGENT_HOOK_PORT "$__hiveward_endpoint_path")',
    '  if [ -n "${HIVEWARD_AGENT_HOOK_PORT:-}" ] && [ -n "$__hiveward_endpoint_port" ] && [ "$__hiveward_endpoint_port" != "$HIVEWARD_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __hiveward_endpoint_name in HIVEWARD_AGENT_HOOK_PORT HIVEWARD_AGENT_HOOK_TOKEN HIVEWARD_AGENT_HOOK_ENV HIVEWARD_AGENT_HOOK_VERSION; do',
    '    eval "__hiveward_current=\\${$__hiveward_endpoint_name:-}"',
    '    [ -z "$__hiveward_current" ] || continue',
    '    __hiveward_endpoint_value=$(__hiveward_endpoint_value "$__hiveward_endpoint_name" "$__hiveward_endpoint_path")',
    '    [ -n "$__hiveward_endpoint_value" ] && export "$__hiveward_endpoint_name=$__hiveward_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __hiveward_name in HIVEWARD_AGENT_HOOK_ENDPOINT HIVEWARD_AGENT_HOOK_PORT HIVEWARD_AGENT_HOOK_TOKEN HIVEWARD_AGENT_HOOK_ENV HIVEWARD_AGENT_HOOK_VERSION HIVEWARD_PANE_KEY HIVEWARD_TAB_ID HIVEWARD_WORKTREE_ID HIVEWARD_AGENT_LAUNCH_TOKEN; do',
    '  __hiveward_fill_from_ancestor "$__hiveward_name"',
    'done',
    'if [ -n "$HIVEWARD_AGENT_HOOK_ENDPOINT" ] && [ -r "$HIVEWARD_AGENT_HOOK_ENDPOINT" ]; then',
    '  __hiveward_fill_from_endpoint_file "$HIVEWARD_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$HIVEWARD_AGENT_HOOK_TOKEN" ] && [ -n "$HIVEWARD_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/hiveward-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/hiveward-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/hiveward-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/hiveward-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/hiveward-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/hiveward-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/hiveward/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/hiveward/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^HIVEWARD_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$HIVEWARD_AGENT_HOOK_PORT" ]; then',
    '      __hiveward_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$HIVEWARD_AGENT_HOOK_PORT" ] || [ -z "$HIVEWARD_AGENT_HOOK_TOKEN" ] || [ -z "$HIVEWARD_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${HIVEWARD_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-HiveWard-Agent-Hook-Token: ${HIVEWARD_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${HIVEWARD_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${HIVEWARD_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${HIVEWARD_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${HIVEWARD_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${HIVEWARD_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${HIVEWARD_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
